def make_images():
    from PIL import Image
    src = os.path.join(ROOT, "site", "assets", "img")
    dst = os.path.join(OUT, "rsya-images")
    os.makedirs(dst, exist_ok=True)
    pairs = {
        "divan": "himchistka-divana-kaliningrad-1600.jpg",
        "mebel": "vyezdnaya-himchistka-mebeli-kaliningrad-1600.jpg",
        "matras": "himchistka-matrasa-kaliningrad-1600.jpg",
        "zapah": "himchistka-nepriyatnogo-zapaha-kaliningrad-1600.jpg",
        "do-posle": "himchistka-mebeli-do-i-posle-1-posle.jpg",
    }
    for name, f in pairs.items():
        im = Image.open(os.path.join(src, f)).convert("RGB")
        w, h = im.size
        # 16:9
        nh = int(w * 9 / 16)
        if nh <= h:
            top = (h - nh) // 2
            wide = im.crop((0, top, w, top + nh))
        else:
            nw = int(h * 16 / 9)
            left = (w - nw) // 2
            wide = im.crop((left, 0, left + nw, h))
        wide = wide.resize((1600, 900) if wide.size[0] >= 1600 else (1080, 607))
        wide.save(os.path.join(dst, f"rsya-{name}-16x9.jpg"), quality=88)
        s = min(w, h)
        sq = im.crop(((w - s) // 2, (h - s) // 2, (w - s) // 2 + s, (h - s) // 2 + s))
        sq = sq.resize((1000, 1000) if s >= 1000 else (600, 600))
        sq.save(os.path.join(dst, f"rsya-{name}-1x1.jpg"), quality=88)


