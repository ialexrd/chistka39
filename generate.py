def main():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(os.path.join(OUT, "assets", "css"), exist_ok=True)
    os.makedirs(os.path.join(OUT, "assets", "js"), exist_ok=True)

    # Удаляем ранее сгенерированные html-страницы (на случай переименования слагов),
    # ассеты в assets/ не трогаем.
    for stale in glob.glob(os.path.join(OUT, "*.html")):
        os.remove(stale)

    all_paths = []

    def write(path, content):
        with open(os.path.join(OUT, path), "w", encoding="utf-8") as f:
            f.write(content)
        all_paths.append(path)
        print_done(path)

    print("Генерация страниц услуг...")
    for s in SERVICES:
        p, c = render_service_page(s)
        write(p, c)

    print("Генерация основных страниц...")
    for renderer in (render_index, render_uslugi, render_onas, render_ceny, render_kontakty, render_privacy):
        p, c = renderer()
        write(p, c)

    # sitemap.xml
    today = date.today().isoformat()
    urls = "".join(
        f"<url><loc>{url(p)}</loc><lastmod>{today}</lastmod></url>" for p in all_paths
    )
    sitemap = f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">{urls}</urlset>'
    with open(os.path.join(OUT, "sitemap.xml"), "w", encoding="utf-8") as f:
        f.write(sitemap)
    print_done("sitemap.xml")

    # robots.txt
    robots = f"User-agent: *\nAllow: /\nSitemap: {url('sitemap.xml')}\n"
    with open(os.path.join(OUT, "robots.txt"), "w", encoding="utf-8") as f:
        f.write(robots)
    print_done("robots.txt")

    print(f"\nГотово! Сгенерировано страниц: {len(all_paths)}")

if __name__ == "__main__":
    main()
